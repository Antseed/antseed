#!/usr/bin/env node
// Pins the TEE seller image to one released CLI: writes package.json with exact versions of
// @antseed/cli, every provider plugin (their current npm release) and the verifier version that
// CLI pins, then regenerates package-lock.json. The image installs exactly this lock with
// `npm ci`, so a commit fully determines the code in the image.
//
//   node deploy/tee-seller/update-lock.mjs <cli version>
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const cliVersion = process.argv[2]
if (!/^\d+\.\d+\.\d+$/.test(cliVersion ?? '')) {
  console.error('usage: node deploy/tee-seller/update-lock.mjs <cli version>')
  process.exit(1)
}

// The provider plugins buyers accept in a TEE seller config, and their shared core.
const teeProviderPlugins = JSON.parse(readFileSync(new URL('../../packages/antseed-verifier/src/tee-provider-plugins.json', import.meta.url), 'utf8'))
const PLUGINS = [...Object.keys(teeProviderPlugins).map((name) => `@antseed/provider-${name}`), '@antseed/provider-core']

const npm = (args, cwd = here) => execFileSync('npm', args, { cwd, encoding: 'utf8' }).trim()

// The verifier version this CLI release pins (it refuses any other), read from its published registry.
const tmp = mkdtempSync(join(tmpdir(), 'tee-seller-lock-'))
let verifierVersion
try {
  const tarball = npm(['pack', `@antseed/cli@${cliVersion}`, '--pack-destination', tmp, '--silent'], tmp)
  // package.json too, so Node loads the registry as ESM.
  execFileSync('tar', ['-xzf', join(tmp, tarball), '-C', tmp, 'package/package.json', 'package/dist/plugins/registry.js'])
  const { TRUSTED_VERIFIER_PLUGINS } = await import(pathToFileURL(join(tmp, 'package/dist/plugins/registry.js')).href)
  verifierVersion = TRUSTED_VERIFIER_PLUGINS.find((plugin) => plugin.package === '@antseed/antseed-verifier')?.version
} finally {
  rmSync(tmp, { recursive: true, force: true })
}
if (!verifierVersion) throw new Error(`could not read the verifier version @antseed/cli@${cliVersion} pins`)

const dependencies = { '@antseed/cli': cliVersion, '@antseed/antseed-verifier': verifierVersion }
for (const name of PLUGINS) dependencies[name] = npm(['view', name, 'version'])

writeFileSync(join(here, 'package.json'), `${JSON.stringify({
  name: 'antseed-tee-seller',
  private: true,
  description: 'The exact CLI, plugins and verifier in the TEE seller image (generated by update-lock.mjs)',
  dependencies: Object.fromEntries(Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b))),
}, null, 2)}\n`)
rmSync(join(here, 'package-lock.json'), { force: true })
npm(['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'])
console.log(`Pinned @antseed/cli@${cliVersion} with @antseed/antseed-verifier@${verifierVersion}`)
